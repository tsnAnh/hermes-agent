#!/usr/bin/env python3
"""Vendor faker-kit into a repository, so every agent session, cloud ones included, has its skills.

Cloud sessions start from a clone of the repository and nothing else. Claude Code cloud sessions do
not install the plugins a repository enables in .claude/settings.json, and they cannot clone a
private kit. So the kit travels inside the repository instead:

  .agents/faker-kit/plugins/<plugin>/   each kit plugin at one commit, without docs/, assets/, or the
                                        kit's own test/ (licenses kept)
  .agents/faker-kit/KIT.json            that commit, and the SHA-256 of every vendored file
  .agents/faker-kit/vendor_kit.py       this script, so the repository can check its own copy
  .claude/skills/<skill>                links into the copy, for Claude Code
  .agents/skills/<skill>                links into the copy, for agents that read that folder
  .claude/agents/<agent>.md             links to the plugins' subagents, for Claude Code

A link never replaces a file or folder the repository already has, such as its own verification
skill: when the repository has its own skill of a name in any of the link folders, the kit's skill
of that name is linked in none of them, so every agent runs the same one. Running again at another
commit replaces the copy and its links, removes stale ones, and moves kit_ref in .agents/dispatch.json.

  python3 vendor_kit.py --kit <kit checkout> --into <repository>    write or refresh the copy
  python3 .agents/faker-kit/vendor_kit.py --check .                  verify it; CI runs this on every pull request

Standard library only, Python 3.9+.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

VENDOR_DIR = ".agents/faker-kit"
MANIFEST = f"{VENDOR_DIR}/KIT.json"
MANIFEST_VERSION = 1
LINK_DIRS = {
    "skills": ((".claude/skills", "../../"), (".agents/skills", "../../")),
    "agents": ((".claude/agents", "../../"),),
}
SKIP_AT_PLUGIN_ROOT = {"docs", "assets", "test"}
SKIP_ANYWHERE = {"node_modules", ".git", "__pycache__", ".DS_Store"}
DISPATCH = ".agents/dispatch.json"
# Re-includes everything under the copy, so a repository's own ignore rules (such as lib/ or build/)
# cannot leave vendored files out of a commit.
GITIGNORE = "# Generated by vendor_kit.py: keep every vendored file, whatever the repository ignores.\n!*\n!*/\n"
README = """# Vendored faker-kit

Generated. Do not edit anything under this folder by hand; `check` fails if it changes.

This is faker-kit at the commit in `KIT.json`, copied in so that every agent session, including
cloud sessions that start from a bare clone, has the kit's skills. The skills are linked from
`.claude/skills/` and `.agents/skills/`, and the subagents from `.claude/agents/`.

To move to another kit commit, run `faker-kit vendor --project <project>` on the Hermes machine, or, from a kit
checkout at that commit, `python3 plugins/trust-ladder/skills/setup-cloud-agents/scripts/vendor_kit.py
--kit . --into <this repository>`, and merge the pull request.

The vendored plugins keep their own `LICENSE` files. `NOTICE.md` says where each comes from.
"""


class VendorError(Exception):
    pass


@dataclass
class Plan:
    kit_ref: str
    files: dict[str, tuple[bytes, bool]] = field(default_factory=dict)  # repository path -> (content, executable)
    links: list[tuple[str, str]] = field(default_factory=list)  # repository path -> relative link target

    def manifest(self, linked: list[tuple[str, str]]) -> bytes:
        files = {path[len(VENDOR_DIR) + 1:]: hashlib.sha256(data).hexdigest() for path, (data, _) in sorted(self.files.items())}
        body = {"version": MANIFEST_VERSION, "kit_ref": self.kit_ref, "files": files, "links": dict(sorted(linked))}
        return (json.dumps(body, indent=1, sort_keys=True) + "\n").encode()


def kit_commit(kit: Path, allow_dirty: bool = False) -> str:
    def git(*args):  # noqa: ANN002, ANN202
        done = subprocess.run(["git", "-C", str(kit), *args], capture_output=True, text=True)
        if done.returncode:
            raise VendorError(f"{kit} is not a git checkout of the kit")
        return done.stdout.strip()

    changed = [line for line in git("status", "--porcelain", "--untracked-files=all", "--", "plugins", "NOTICE.md", "LICENSE").splitlines()
               if not any(part in SKIP_ANYWHERE for part in line[3:].split("/"))]
    if changed and not allow_dirty:
        raise VendorError(f"{kit} has uncommitted changes under plugins/; commit them or check out a clean commit")
    return git("rev-parse", "HEAD")


def plugin_order(kit: Path) -> list[str]:
    """trust-ladder first, team-workflows last, so a skill several plugins share comes from the one
    docs/catalog.json prefers, as in install-kit-skills.sh."""
    names = sorted(p.name for p in (kit / "plugins").iterdir() if p.is_dir())
    if not names:
        raise VendorError(f"no plugins under {kit / 'plugins'}")
    rest = [n for n in names if n not in ("trust-ladder", "team-workflows")]
    return [n for n in ("trust-ladder",) if n in names] + rest + [n for n in ("team-workflows",) if n in names]


def kit_files(kit: Path) -> list[str]:
    """The kit's files under plugins/ that git tracks or would track: never ignored build output."""
    done = subprocess.run(["git", "-C", str(kit), "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", "plugins"],
                          capture_output=True)
    if done.returncode:
        raise VendorError(f"{kit} is not a git checkout of the kit")
    return sorted({p for p in done.stdout.decode().split("\0") if p})


def plan(kit: Path, kit_ref: str) -> Plan:
    out = Plan(kit_ref=kit_ref)
    order = {name: i for i, name in enumerate(plugin_order(kit))}
    chosen = []
    for rel in kit_files(kit):
        parts = rel.split("/")
        if len(parts) < 3 or parts[1] not in order or any(part in SKIP_ANYWHERE for part in parts):
            continue
        if len(parts) > 3 and parts[2] in SKIP_AT_PLUGIN_ROOT:
            continue
        source = kit / rel
        if source.is_symlink():
            raise VendorError(f"{source} is a symlink; the vendored copy holds files only")
        if source.is_file():
            chosen.append((order[parts[1]], rel))
    for _, rel in sorted(chosen):
        source = kit / rel
        out.files[f"{VENDOR_DIR}/{rel}"] = (source.read_bytes(), os.access(source, os.X_OK))
    for extra in ("LICENSE", "NOTICE.md"):
        if (kit / extra).is_file():
            out.files[f"{VENDOR_DIR}/{extra}"] = ((kit / extra).read_bytes(), False)
    out.files[f"{VENDOR_DIR}/README.md"] = (README.encode(), False)
    out.files[f"{VENDOR_DIR}/.gitignore"] = (GITIGNORE.encode(), False)
    out.files[f"{VENDOR_DIR}/vendor_kit.py"] = (Path(__file__).read_bytes(), True)

    seen: set[str] = set()
    for name in plugin_order(kit):
        for kind, places in LINK_DIRS.items():
            folder = kit / "plugins" / name / kind
            if not folder.is_dir():
                continue
            for entry in sorted(folder.iterdir()):
                vendored = f"{VENDOR_DIR}/plugins/{name}/{kind}/{entry.name}"
                if kind == "skills" and f"{vendored}/SKILL.md" not in out.files:
                    continue
                if kind == "agents" and (entry.suffix != ".md" or vendored not in out.files):
                    continue
                for link_dir, up in places:
                    path = f"{link_dir}/{entry.name}"
                    if path in seen:
                        continue
                    seen.add(path)
                    out.links.append((path, f"{up}{VENDOR_DIR}/plugins/{name}/{kind}/{entry.name}"))
    return out


def points_into_vendor(target: str) -> bool:
    """Whether a link in one of the link folders is one this script made."""
    return target.startswith(f"../../{VENDOR_DIR}/plugins/")


def foreign_kit_links(repo: Path) -> list[str]:
    found = []
    for link_dir in sorted({place for places in LINK_DIRS.values() for place, _ in places}):
        folder = repo / link_dir
        if not folder.is_dir():
            continue
        for entry in sorted(folder.iterdir()):
            if not entry.is_symlink():
                continue
            target = entry.readlink().as_posix()
            parts = [part for part in target.split("/") if part != ".."]
            if parts[:1] == [".agents"] and parts[2:3] == ["plugins"] and not points_into_vendor(target):
                found.append(f"{entry.relative_to(repo).as_posix()} -> {target}")
    return found


def link_key(path: str) -> tuple[str, str]:
    """A link's kind and name: a skill of one name is one skill, whichever folder links it."""
    return ("agents" if path.startswith(".claude/agents/") else "skills", path.rsplit("/", 1)[1])


def choose_links(links: list[tuple[str, str]], own) -> tuple[list[tuple[str, str]], list[str]]:  # noqa: ANN001
    """Split the planned links into those to write and those to skip. own(path) says whether the
    repository has its own entry at path. A name the repository has its own entry for anywhere is
    linked nowhere, so every agent runs the repository's skill."""
    taken = {link_key(path) for path, _ in links if own(path)}
    linked = [(path, target) for path, target in links if link_key(path) not in taken]
    skipped = [path for path, _ in links if link_key(path) in taken]
    return linked, skipped


def move_kit_ref(text: str, kit_ref: str) -> str | None:
    """.agents/dispatch.json with kit_ref moved to the vendored commit, or None if it already is."""
    try:
        config = json.loads(text)
    except ValueError:
        raise VendorError(f"{DISPATCH} is not valid JSON; fix it first") from None
    if not isinstance(config, dict):
        raise VendorError(f"{DISPATCH} is not a JSON object; fix it first")
    if config.get("kit_ref") == kit_ref:
        return None
    config["kit_ref"] = kit_ref
    return json.dumps(config, indent=2) + "\n"


# Applying to a working tree -----------------------------------------------------------------------


def apply(kit: Path, repo: Path, allow_dirty: bool = False) -> dict:
    if not (repo / ".git").exists():
        raise VendorError(f"{repo} is not a git repository")
    for link_dir in {place for places in LINK_DIRS.values() for place, _ in places}:
        if (repo / link_dir).is_symlink():
            raise VendorError(f"{link_dir} is a symlink; make it a real folder first, so the kit's relative links resolve")
    foreign = foreign_kit_links(repo)
    if foreign:
        raise VendorError("these links point into another vendored kit folder, so its skills would stay in use: " + ", ".join(foreign[:5])
                          + "; delete those links and that folder, then run again")
    p = plan(kit, kit_commit(kit, allow_dirty))
    vendor = repo / VENDOR_DIR
    wanted = set(p.files)
    if vendor.exists():
        for current, _, files in os.walk(vendor):
            for file in files:
                path = Path(current) / file
                rel = path.relative_to(repo).as_posix()
                if rel not in wanted and rel != MANIFEST:
                    path.unlink()
        for current, dirs, files in sorted(os.walk(vendor), key=lambda t: -len(t[0])):
            if not dirs and not files and Path(current) != vendor:
                Path(current).rmdir()
    for rel, (data, executable) in p.files.items():
        target = repo / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        target.chmod(0o755 if executable else 0o644)

    def own(path: str) -> bool:
        where = repo / path
        return not points_into_vendor(os.readlink(where)) if where.is_symlink() else where.exists()  # noqa: PTH115

    linked, skipped = choose_links(p.links, own)
    planned = {path for path, _ in linked}
    for path, link_target in linked:
        where = repo / path
        if where.is_symlink():
            where.unlink()
        where.parent.mkdir(parents=True, exist_ok=True)
        where.symlink_to(link_target)
    removed = []
    for link_dir, _ in {place for places in LINK_DIRS.values() for place in places}:
        folder = repo / link_dir
        if not folder.is_dir():
            continue
        for entry in folder.iterdir():
            rel = entry.relative_to(repo).as_posix()
            if entry.is_symlink() and points_into_vendor(os.readlink(entry)) and rel not in planned:  # noqa: PTH115
                entry.unlink()
                removed.append(rel)
    (repo / MANIFEST).write_bytes(p.manifest(linked))
    dispatch = repo / DISPATCH
    moved = dispatch.is_file() and move_kit_ref(dispatch.read_text(), p.kit_ref)
    if moved:
        dispatch.write_text(moved)
    ignored = ignored_paths(repo, [*p.files, MANIFEST, *planned])
    if ignored:
        shown = ", ".join(ignored[:5]) + (f", and {len(ignored) - 5} more" if len(ignored) > 5 else "")
        raise VendorError(f"the repository's ignore rules leave out {shown}; un-ignore .agents/faker-kit/ and the link folders, then run again")
    return {"kit_ref": p.kit_ref, "files": len(p.files), "links": len(linked), "skipped": skipped, "removed": sorted(removed), "kit_ref_moved": bool(moved)}


def ignored_paths(repo: Path, paths: list[str]) -> list[str]:
    done = subprocess.run(["git", "-C", str(repo), "check-ignore", "--no-index", "--stdin", "-z"],
                          input="\0".join(paths).encode(), capture_output=True)
    if done.returncode not in (0, 1):
        raise VendorError(f"git check-ignore failed in {repo}")
    return sorted(p for p in done.stdout.decode().split("\0") if p)


# Checking a working tree --------------------------------------------------------------------------


def check(repo: Path) -> list[str]:
    problems = []
    try:
        manifest = json.loads((repo / MANIFEST).read_text())
    except (OSError, ValueError):
        return [f"{MANIFEST} is missing or not JSON; vendor the kit first"]
    if manifest.get("version") != MANIFEST_VERSION:
        return [f"{MANIFEST} is version {manifest.get('version')}, not {MANIFEST_VERSION}"]
    files = manifest.get("files") or {}
    vendor = repo / VENDOR_DIR
    for rel, digest in sorted(files.items()):
        path = vendor / rel
        if path.is_symlink() or not path.is_file():
            problems.append(f"{VENDOR_DIR}/{rel} is missing")
        elif hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            problems.append(f"{VENDOR_DIR}/{rel} differs from the kit at {manifest.get('kit_ref', '?')[:12]}; do not edit the vendored kit")
    for current, _, names in os.walk(vendor):
        for name in names:
            rel = (Path(current) / name).relative_to(vendor).as_posix()
            if rel != "KIT.json" and rel not in files and "__pycache__" not in rel:
                problems.append(f"{VENDOR_DIR}/{rel} is not part of the vendored kit")
    for path, target in sorted((manifest.get("links") or {}).items()):
        where = repo / path
        if not where.is_symlink() or os.readlink(where) != target:  # noqa: PTH115
            problems.append(f"{path} should link to {target}")
        elif not where.exists():
            problems.append(f"{path} links to {target}, which does not exist")
    problems.extend(f"{link} points into another vendored kit folder; delete it" for link in foreign_kit_links(repo))
    dispatch = repo / ".agents" / "dispatch.json"
    if dispatch.is_file():
        try:
            pinned = json.loads(dispatch.read_text()).get("kit_ref")
        except ValueError:
            pinned = None
        if pinned and pinned != manifest.get("kit_ref"):
            problems.append(f".agents/dispatch.json kit_ref {str(pinned)[:12]} differs from the vendored kit {manifest.get('kit_ref', '?')[:12]}")
    return problems


def main(argv: list[str] | None = None) -> int:
    top = argparse.ArgumentParser(prog="vendor_kit.py", description=__doc__.split("\n\n", 1)[0])
    top.add_argument("--kit", type=Path, help="a checkout of the kit at the commit to vendor")
    top.add_argument("--into", type=Path, help="the repository to vendor it into")
    top.add_argument("--check", type=Path, metavar="REPO", help="verify a repository's vendored kit")
    top.add_argument("--allow-dirty", action="store_true", help="vendor a kit checkout with uncommitted changes")
    args = top.parse_args(argv)
    try:
        if args.check:
            problems = check(args.check)
            for problem in problems:
                print(f"vendor_kit: {problem}", file=sys.stderr)
            if not problems:
                print("vendor_kit: the vendored kit matches KIT.json")
            return 1 if problems else 0
        if not (args.kit and args.into):
            top.error("give --kit and --into, or --check")
        result = apply(args.kit.resolve(), args.into.resolve(), args.allow_dirty)
    except VendorError as err:
        print(f"vendor_kit: {err}", file=sys.stderr)
        return 1
    print(json.dumps(result))
    for path in result["skipped"]:
        print(f"vendor_kit: kept the repository's own {path}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
